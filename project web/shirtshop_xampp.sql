SET NAMES utf8mb4;
SET time_zone = '+07:00';
SET FOREIGN_KEY_CHECKS = 0;

-- ไม่ใช้ DROP DATABASE เพราะ phpMyAdmin ไม่ยอมให้ผู้ใช้ที่ไม่ใช่ root รัน (เช่น shop ใน Docker)
CREATE DATABASE IF NOT EXISTS shopdb;
USE shopdb;
ALTER DATABASE shopdb CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

DROP TABLE IF EXISTS stock_movements, order_items, orders, coupons,
  promotion_bundle_items, promotion_tiers, promotions,
  product_images, product_variants, products, categories, addresses, users;

-- MySQL 8 | ร้านขายเสื้อ : schema + seed สำหรับทดสอบ query

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  first_name VARCHAR(50) NOT NULL,
  last_name  VARCHAR(50) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  phone VARCHAR(10) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('customer','admin') NOT NULL DEFAULT 'customer',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE addresses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  street VARCHAR(200) NOT NULL,
  subdistrict VARCHAR(80) NOT NULL,
  district VARCHAR(80) NOT NULL,
  province VARCHAR(80) NOT NULL,
  postal_code CHAR(5) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE categories (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE products (
  id INT AUTO_INCREMENT PRIMARY KEY,
  category_id INT NOT NULL,
  name VARCHAR(100) NOT NULL,
  description TEXT,
  base_price DECIMAL(10,2) NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,   -- 0 = ปิดขาย ลูกค้าไม่เห็นในร้าน
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (category_id) REFERENCES categories(id)
);

-- สินค้า 1 ชิ้นมีได้หลายรูป รูปที่ sort_order น้อยสุดเป็นรูปหลัก
CREATE TABLE product_images (
  id INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  filename VARCHAR(255) NOT NULL,           -- ชื่อไฟล์ใน uploads/products/
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE product_variants (
  id INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  size ENUM('S','M','L','XL') NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  UNIQUE (product_id, size),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

-- โปรโมชั่นคิดจากสินค้าทั้งตะกร้า และใช้โปรที่ลดได้มากที่สุดเพียงโปรเดียวต่อออเดอร์ (ดู includes/pricing.php)
CREATE TABLE promotions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  type ENUM('buy_x_get_y','timed_discount','volume','bundle') NOT NULL,
  category_id INT NULL,                     -- หมวดที่ร่วมโปร NULL = ทุกหมวด (bundle ใช้ promotion_bundle_items แทน)
  discount_type ENUM('percent','fixed') NULL,   -- timed_discount
  discount_value DECIMAL(10,2) NULL,            -- timed_discount : % หรือบาทต่อชิ้น
  buy_qty INT NULL,                             -- buy_x_get_y
  free_qty INT NULL,                            -- buy_x_get_y
  bundle_price DECIMAL(10,2) NULL,              -- bundle : ราคาต่อ 1 เซ็ต
  start_at DATETIME NULL,
  end_at DATETIME NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (category_id) REFERENCES categories(id)
);

-- volume : ขั้นส่วนลดตามจำนวนชิ้น ใช้ขั้นสูงสุดที่ซื้อถึง
CREATE TABLE promotion_tiers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  promotion_id INT NOT NULL,
  min_qty INT NOT NULL,
  discount_percent DECIMAL(5,2) NOT NULL,
  UNIQUE (promotion_id, min_qty),
  FOREIGN KEY (promotion_id) REFERENCES promotions(id) ON DELETE CASCADE
);

-- bundle : ส่วนประกอบของ 1 เซ็ต เช่น เสื้อยืด 1 ตัว + โปโล 1 ตัว
CREATE TABLE promotion_bundle_items (
  promotion_id INT NOT NULL,
  category_id INT NOT NULL,
  qty INT NOT NULL DEFAULT 1,
  PRIMARY KEY (promotion_id, category_id),
  FOREIGN KEY (promotion_id) REFERENCES promotions(id) ON DELETE CASCADE,
  FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE coupons (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  discount_type ENUM('percent','fixed') NOT NULL,
  discount_value DECIMAL(10,2) NOT NULL,
  min_total DECIMAL(10,2) NOT NULL DEFAULT 0,
  max_uses INT NULL,
  expires_at DATETIME NULL
);

CREATE TABLE orders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  address_id INT NOT NULL,
  coupon_id INT NULL,
  status ENUM('pending','paid','preparing','shipped','completed','cancelled','expired') NOT NULL DEFAULT 'pending',
  payment_method ENUM('qr','cod') NOT NULL,
  subtotal DECIMAL(10,2) NOT NULL,
  discount_total DECIMAL(10,2) NOT NULL DEFAULT 0,
  shipping_fee DECIMAL(10,2) NOT NULL DEFAULT 0,
  net_total DECIMAL(10,2) NOT NULL,
  tracking_no VARCHAR(40) NULL,
  slip_image VARCHAR(255) NULL,             -- path ใน uploads/slips/ ที่ลูกค้าอัปโหลด
  paid_at DATETIME NULL,                    -- เวลาที่แอดมินยืนยันการชำระเงิน
  cancel_reason VARCHAR(200) NULL,          -- แสดงให้ลูกค้าเห็น เช่น "ยอดในสลิปไม่ตรง"
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (address_id) REFERENCES addresses(id),
  FOREIGN KEY (coupon_id) REFERENCES coupons(id)
);

CREATE TABLE order_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  variant_id INT NOT NULL,
  promotion_id INT NULL,
  qty INT NOT NULL,
  unit_price_paid DECIMAL(10,2) NOT NULL,
  discount_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (order_id) REFERENCES orders(id),
  FOREIGN KEY (variant_id) REFERENCES product_variants(id),
  FOREIGN KEY (promotion_id) REFERENCES promotions(id)
);

CREATE TABLE stock_movements (
  id INT AUTO_INCREMENT PRIMARY KEY,
  variant_id INT NOT NULL,
  order_id INT NULL,
  type ENUM('in','out') NOT NULL,
  qty INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (variant_id) REFERENCES product_variants(id),
  FOREIGN KEY (order_id) REFERENCES orders(id)
);

